// spec.md -> Kane CLI _test.md files.
// A requirement is an H2 of the form "## R<n>: <title>"; each "- " bullet under it is one step.
import fs from "node:fs";
import path from "node:path";

export function slugify(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 48);
}

export function parseSpec(text) {
  const reqs = [];
  let cur = null;
  for (const raw of text.split(/\r?\n/)) {
    const h = raw.match(/^##\s+(R\d+)\s*[:\-—]\s*(.+?)\s*$/i);
    if (h) {
      cur = { id: h[1].toUpperCase(), title: h[2], steps: [] };
      reqs.push(cur);
      continue;
    }
    if (/^#{1,2}\s/.test(raw)) { cur = null; continue; }
    if (!cur) continue;
    const b = raw.match(/^\s*[-*]\s+(.+)$/);
    if (b) cur.steps.push(b[1].trim());
    else if (raw.trim() && cur.steps.length) cur.steps[cur.steps.length - 1] += " " + raw.trim();
  }
  return reqs;
}

export function lintSpec(reqs) {
  const problems = [];
  const seen = new Set();
  for (const r of reqs) {
    if (seen.has(r.id)) problems.push(`${r.id}: duplicate requirement id`);
    seen.add(r.id);
    if (!r.steps.length) problems.push(`${r.id}: has no steps`);
    const lastStep = r.steps[r.steps.length - 1] || "";
    if (!/\b(verify|assert|check|confirm)\b/i.test(lastStep)) {
      problems.push(`${r.id}: last step must verify something (start it with "Verify ...")`);
    }
  }
  return problems;
}

export function testFileName(req) {
  return `${req.id.toLowerCase()}-${slugify(req.title)}_test.md`;
}

export function renderTest(req, { url }) {
  const steps = [
    // Every test starts from an empty group, whatever an earlier test left in storage.
    `## Start from an empty group\nOpen ${url}, click "Start over", and verify the Members list says No members yet.`,
    ...req.steps.map((s, i) => `## Step ${i + 1}\n${s}`),
  ];
  return [
    "---",
    "mode: testing",
    `url: ${url}`,
    `tags: [specloop, ${req.id.toLowerCase()}]`,
    "max_steps: 40",
    "timeout: 240",
    "---",
    "",
    `# ${req.id}: ${req.title}`,
    "",
    `Generated by SpecLoop from spec.md (${req.id}). Edit spec.md, not this file, then run \`npm run gen\`.`,
    "",
    steps.join("\n\n"),
    "",
  ].join("\n");
}

// Writes tests/<id>-<slug>_test.md. Removes generated tests whose requirement is gone.
// Recorded output-<stem>/ folders are kept when a test's text did not change, and
// dropped when it did, so Kane re-authors the steps instead of replaying stale ones.
export function generate({ specPath, outDir, url }) {
  const reqs = parseSpec(fs.readFileSync(specPath, "utf8"));
  const problems = lintSpec(reqs);
  if (problems.length) return { reqs, problems, written: [], removed: [] };
  fs.mkdirSync(outDir, { recursive: true });
  const wanted = new Set();
  const written = [];
  for (const r of reqs) {
    const name = testFileName(r);
    wanted.add(name);
    const file = path.join(outDir, name);
    const body = renderTest(r, { url });
    const old = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (old !== body) {
      fs.writeFileSync(file, body);
      written.push(file);
      const rec = path.join(outDir, `output-${name.replace(/_test\.md$/, "")}`);
      if (old !== null && fs.existsSync(rec)) fs.rmSync(rec, { recursive: true, force: true });
    }
  }
  const removed = [];
  for (const f of fs.readdirSync(outDir)) {
    if (/^r\d+-.*_test\.md$/.test(f) && !wanted.has(f)) {
      fs.rmSync(path.join(outDir, f));
      removed.push(f);
    }
  }
  return { reqs, problems, written, removed };
}

export function reqIdFromPath(p) {
  const m = path.basename(String(p || "")).match(/^(r\d+)-/i);
  return m ? m[1].toUpperCase() : null;
}
